// dotnetUnicode is testdata/dotnet-unicode-bmp.json, dumped from pwsh by oracle/unicode-bmp.ps1.
type dotnetUnicode struct {
	Version      string
	Uppercase    [][2]int
	CategoryRuns [][2]int
}

func loadDotnetUnicode(t *testing.T) *dotnetUnicode {
	t.Helper()
	b, err := os.ReadFile("testdata/dotnet-unicode-bmp.json")
	if err != nil {
		t.Skip("no .NET Unicode dump:", err)
	}
	var d dotnetUnicode
	if err := json.Unmarshal(b, &d); err != nil {
		t.Fatal(err)
	}
	return &d
}

// netClassOfCategory maps a .NET UnicodeCategory number onto the classes the tokenizer asks about.
func netClassOfCategory(cat int) netClass {
	switch {
	case cat <= 4:
		return netLetter
	case cat == 8:
		return netDigit
	case cat >= 11 && cat <= 13:
		return netSeparator
	}
	return netOther
}

// goNetClass is netClassOf without the overrides.
func goNetClass(c uint16) netClass {
	if isSurrogate(c) {
		return netOther
	}
	r := rune(c)
	switch {
	case unicode.IsLetter(r):
		return netLetter
	case unicode.Is(unicode.Nd, r):
		return netDigit
	case unicode.In(r, unicode.Zs, unicode.Zl, unicode.Zp):
		return netSeparator
	}
	return netOther
}

// goUpper is upperOrdinalUnit without the overrides.
func goUpper(c uint16) uint16 {
	if isSurrogate(c) {
		return c
	}
	u := unicode.ToUpper(rune(c))
	if u > 0xffff {
		return c
	}
	return uint16(u)
}

// TestDotnetUnicodeParity holds the char classes and the OrdinalIgnoreCase upper-casing to .NET's own tables.
// PSPARSE_UPDATE_UNICODE=1 rewrites chartraits_tables.go from the dump instead.
func TestDotnetUnicodeParity(t *testing.T) {
	d := loadDotnetUnicode(t)
	cats := make([]int, 0x10000)
	for i, run := range d.CategoryRuns {
		end := 0x10000
		if i+1 < len(d.CategoryRuns) {
			end = d.CategoryRuns[i+1][0]
		}
		for c := run[0]; c < end; c++ {
			cats[c] = run[1]
		}
	}
	upper := make([]uint16, 0x10000)
	for c := range upper {
		upper[c] = uint16(c)
	}
	for _, m := range d.Uppercase {
		upper[m[0]] = uint16(m[1])
	}
	// OrdinalIgnoreCase keeps U+017F apart from s although ToUpperInvariant maps it to S (the dump's
	// OrdinalComparisons record it), so the ordinal table drops every mapping onto ASCII.
	for c := 128; c < 0x10000; c++ {
		if upper[c] < 128 {
			upper[c] = uint16(c)
		}
	}

	classOver := map[uint16]netClass{}
	upperOver := map[uint16]uint16{}
	for c := 0; c < 0x10000; c++ {
		u := uint16(c)
		if want := netClassOfCategory(cats[c]); goNetClass(u) != want {
			classOver[u] = want
		}
		if c >= 128 && goUpper(u) != upper[c] && !(goUpper(u) < 128 && upper[c] == u) {
			upperOver[u] = upper[c]
		}
	}

	if os.Getenv("PSPARSE_UPDATE_UNICODE") == "1" {
		writeUnicodeTables(t, d.Version, classOver, upperOver)
		return
	}
	for c := 0; c < 0x10000; c++ {
		u := uint16(c)
		if got, want := netClassOf(u), netClassOfCategory(cats[c]); got != want {
			t.Errorf("U+%04X: class %d, .NET %d", c, got, want)
		}
		if got := upperOrdinalUnit(u); c >= 128 && got != upper[c] {
			t.Errorf("U+%04X: upper U+%04X, .NET U+%04X", c, got, upper[c])
		}
	}
}

func writeUnicodeTables(t *testing.T, version string, classOver map[uint16]netClass, upperOver map[uint16]uint16) {
	var b strings.Builder
	b.WriteString("// SPDX-License-Identifier: MPL-2.0\n// Copyright (C) 2026 The Lemongrass Authors\n\n")
	fmt.Fprintf(&b, "// Code generated by TestDotnetUnicodeParity from pwsh %s's char tables; DO NOT EDIT.\n\n", version)
	b.WriteString("package psparse\n\n")
	b.WriteString("// netClassOverrides holds the BMP units whose .NET class differs from Go's unicode tables.\n")
	b.WriteString("var netClassOverrides = map[uint16]netClass{\n")
	for _, c := range sortedKeys(classOver) {
		fmt.Fprintf(&b, "\t0x%04x: %d,\n", c, classOver[c])
	}
	b.WriteString("}\n\n// upperOverrides holds the BMP units whose OrdinalIgnoreCase upper form differs from Go's unicode.ToUpper.\n")
	b.WriteString("var upperOverrides = map[uint16]uint16{\n")
	for _, c := range sortedKeys(upperOver) {
		fmt.Fprintf(&b, "\t0x%04x: 0x%04x,\n", c, upperOver[c])
	}
	b.WriteString("}\n")
	if err := os.WriteFile("chartraits_tables.go", []byte(b.String()), 0o644); err != nil {
		t.Fatal(err)
	}
	t.Logf("wrote %d class and %d upper overrides", len(classOver), len(upperOver))
}

func sortedKeys[V any](m map[uint16]V) []uint16 {
	keys := make([]uint16, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool { return keys[i] < keys[j] })
	return keys
}
